function splitDays(sex, days, split, place = 'gym') {
  const take = cycle => Array.from({ length: days }, (_, i) => cycle[i % cycle.length]);
  if (place !== 'gym') {
    const full = split === 'full' ? days <= 4 : split === 'ul' ? false : days <= 3;
    return take(full ? HOME_CYCLES[place].full : HOME_CYCLES[place].ul[sex]);
  }
  if (split === 'auto' || !SPLIT_CYCLES[split] || !splitOk(split, days)) return SPLITS[sex][days];
  return take(SPLIT_CYCLES[split][sex]);
}
